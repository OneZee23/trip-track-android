#!/usr/bin/env python3
"""iOS: Tools/build_app_icons.py; render D2 unchanged inside Android's 72/108 layout.

Requires Pillow and Chromium (or --resvg-module), only when regenerating. Sources stay in the read-only iOS checkout.
"""
import argparse
import importlib.util
import math
import subprocess
import tempfile
import xml.etree.ElementTree as ET
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
SVG = 'http://www.w3.org/2000/svg'
ANDROID = 'http://schemas.android.com/apk/res/android'
AAPT = 'http://schemas.android.com/aapt'
ET.register_namespace('android', ANDROID)
ET.register_namespace('aapt', AAPT)


def attr(name):
    return '{' + ANDROID + '}' + name


def vector():
    return ET.Element('vector', {attr('width'): '108dp', attr('height'): '108dp',
                              attr('viewportWidth'): '1536', attr('viewportHeight'): '1536'})


def path(parent, data, fill='#000000', alpha='1', stroke=None, width=None):
    attrs = {attr('pathData'): data, attr('fillColor'): fill, attr('fillAlpha'): alpha}
    if stroke:
        attrs.update({attr('strokeColor'): stroke, attr('strokeWidth'): width,
                      attr('strokeLineCap'): 'round', attr('strokeLineJoin'): 'round'})
    return ET.SubElement(parent, 'path', attrs)


def write_xml(destination, root):
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text('<?xml version="1.0" encoding="utf-8"?>\n'
                           '<!-- iOS: Tools/AppIcon/D2.svg; generated by tools/icons/build_android_icons.py. -->\n'
                           + ET.tostring(root, encoding='unicode') + '\n')


def polygon(element):
    return 'M' + ' L'.join(element.attrib['points'].split()) + ' Z'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--ios', type=Path, default=Path.home() / 'OneZeeProjects/trip-track')
    parser.add_argument('--chrome', type=Path)
    parser.add_argument('--resvg-module', type=Path, help='Alternative offline SVG renderer (@resvg/resvg-js)')
    args = parser.parse_args()
    spec = importlib.util.spec_from_file_location('ios_icons', args.ios / 'Tools/build_app_icons.py')
    ios = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(ios)
    cached = sorted((Path.home() / 'Library/Caches/ms-playwright').glob(
        'chromium_headless_shell-*/chrome-headless-shell-mac-*/chrome-headless-shell'), reverse=True)
    chrome = args.chrome or next(iter(cached), Path('/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'))
    if not args.resvg_module and not chrome.is_file():
        parser.error('Chrome not found; pass --chrome or --resvg-module')
    art = ET.fromstring(ios.artwork('D2.svg'))
    scene = list(art)[1]
    background = vector()
    bg = path(background, 'M0,0h1536v1536H0z')
    item = ET.SubElement(bg, '{' + AAPT + '}attr', {'name': 'android:fillColor'})
    ET.SubElement(item, 'gradient', {attr('startX'): '0', attr('startY'): '256', attr('endX'): '0',
                                   attr('endY'): '1280', attr('type'): 'linear',
                                   attr('startColor'): '#F1E6CF', attr('endColor'): '#E6D6B6'})
    bg.attrib.pop(attr('fillColor'))
    group = ET.SubElement(background, 'group', {attr('translateX'): '256', attr('translateY'): '256'})
    for element in list(scene)[1:6]:
        style = dict(part.strip().split(': ', 1) for part in element.attrib['style'].split(';') if part.strip())
        path(group, polygon(element), style['fill'], style.get('opacity', '1'))
    # Android vectors have no dash array. Expand the authored round 1/34 dash into capsules.
    x, y, ex, ey = 1792.5, -29.4, 811.4, 461.2
    length = math.hypot(ex-x, ey-y)
    for offset in range(0, int(length), 35):
        cx, cy = x+(ex-x)*offset/length, y+(ey-y)*offset/length
        path(group, f'M{cx},{cy}l{(ex-x)/length},{(ey-y)/length}', '#00000000', stroke='#C8472D', width='18')
    write_xml(ROOT / 'app/src/main/res/drawable/ic_launcher_background.xml', background)

    tinted_scene = list(ET.fromstring(ios.artwork('D-tinted-preview.svg')))[1]
    car = next(el for el in tinted_scene if 'transform' in el.attrib)
    for debug in (False, True):
        res = ROOT / ('app/src/debug/res' if debug else 'app/src/main/res')
        root = ET.fromstring(ios.artwork('D2.svg', dev=debug))
        root.attrib = {'viewBox': '-256 -256 1536 1536', 'width': '1728', 'height': '1728'}
        for el in list(list(root)[1])[:7]:
            list(root)[1].remove(el)
        with tempfile.TemporaryDirectory(prefix='triptrack-icon-') as tmp:
            work = Path(tmp)
            html = work / 'icon.html'
            html.write_text('<!doctype html><style>html,body{margin:0;background:transparent}svg{display:block}</style>'
                            + ET.tostring(root, encoding='unicode'))
            rendered = work / 'icon.png'
            if args.resvg_module:
                source = work / 'foreground.svg'
                source.write_text(ET.tostring(root, encoding='unicode'))
                subprocess.run(['node', '-e',
                                'const fs=require("fs"); const {Resvg}=require(process.argv[1]); '
                                'fs.writeFileSync(process.argv[3], new Resvg(fs.readFileSync(process.argv[2])).render().asPng());',
                                str(args.resvg_module), str(source), str(rendered)], check=True, timeout=60)
            else:
                subprocess.run([str(chrome), '--headless', '--disable-gpu', '--hide-scrollbars', '--no-first-run',
                                '--disable-background-networking', '--default-background-color=00000000',
                                '--force-device-scale-factor=1', '--window-size=1728,1728',
                                f'--user-data-dir={work / "profile"}', f'--screenshot={rendered}', html.as_uri()],
                               check=True, capture_output=True, timeout=60)
            image = Image.open(rendered).convert('RGBA')
            for density, scale in [('mdpi',1), ('hdpi',1.5), ('xhdpi',2), ('xxhdpi',3), ('xxxhdpi',4)]:
                folder = res / f'drawable-{density}'
                folder.mkdir(parents=True, exist_ok=True)
                image.resize((int(108*scale), int(108*scale)), Image.Resampling.LANCZOS).save(folder / 'ic_launcher_foreground.png')

        mono = vector()
        route = ET.SubElement(mono, 'group', {attr('translateX'): '256', attr('translateY'): '256'})
        for offset in range(0, int(length), 35):
            cx, cy = x+(ex-x)*offset/length, y+(ey-y)*offset/length
            dash = path(route, f'M{cx},{cy}l{(ex-x)/length},{(ey-y)/length}', '#00000000', stroke='#000000', width='18')
            dash.set(attr('strokeAlpha'), str(round((.299*207 + .587*227 + .114*255)/255, 4)))
        transform = ET.SubElement(mono, 'group', {attr('translateX'): '919.15', attr('translateY'): '688.64',
                                                 attr('scaleX'): '114.074', attr('scaleY'): '114.074'})
        for el in car:
            style = dict(part.strip().split(': ', 1) for part in el.attrib['style'].split(';') if part.strip())
            color = style.get('fill', style.get('stroke', '#000000'))
            if color == 'none':
                continue
            rgb = tuple(int(color[i:i+2],16) for i in (1,3,5))
            # iOS's tinted export is grayscale; Android supplies hue and uses this as the alpha mask.
            alpha = sum(c*w for c,w in zip(rgb,(.299,.587,.114)))/255
            path(transform, polygon(el) if el.tag.endswith('polygon') else el.attrib['d'],
                 '#000000', str(round(alpha * float(style.get('opacity',1)),4)))
        if debug:
            badge = ET.SubElement(mono, 'group', {attr('translateX'): '568', attr('translateY'): '358'})
            path(badge, 'M46,0H354Q400,0 400,46V120Q400,166 354,166H46Q0,166 0,120V46Q0,0 46,0Z',
                 '#00000000', stroke='#000000', width='12')
            for data in ['M65 46 V120 H91 C136 120 136 46 91 46 Z', 'M216 46 H158 V120 H216 M158 83 H205',
                         'M254 46 L287 120 H294 L327 46']:
                path(badge, data, '#00000000', stroke='#000000', width='17')
        write_xml(res / 'drawable/ic_launcher_monochrome.xml', mono)

    # minSdk 29 already supports adaptive icons. Both names let the launcher apply its own mask.
    for name in ('ic_launcher', 'ic_launcher_round'):
        for qualifier, monochrome in [('mipmap-anydpi-v26',False), ('mipmap-anydpi-v33',True)]:
            root = ET.Element('adaptive-icon')
            for layer in ['background','foreground'] + (['monochrome'] if monochrome else []):
                ET.SubElement(root, layer, {attr('drawable'): '@drawable/ic_launcher_' + layer})
            write_xml(ROOT / 'app/src/main/res' / qualifier / (name + '.xml'), root)


if __name__ == '__main__':
    main()
