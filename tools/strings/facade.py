"""Typed resource accessors. iOS: directly extractable AppStrings functions."""
from swift import Unsupported, arguments, calls, literal, split

HEADER = '''// Generated by tools/strings/generate.py. iOS: AppStrings*.swift / LiveActivityStrings.swift.
package com.onezee.triptrack.designsystem.strings

import com.onezee.triptrack.designsystem.R

// iOS: AppStrings.swift and AppStringsCore.swift. Logic lives in AppStrings.kt.
abstract class ResourceAppStrings {
    abstract fun tr(id: Int, vararg args: Any): String
    abstract fun plural(id: Int, count: Int, vararg args: Any): String
'''


def parameters(function, live):
    # The parser signature includes the closing ')' and return type.
    tokens = function.signature
    end = next(i for i, t in enumerate(tokens) if t.value == '->')
    tokens = tokens[:end - 1]
    result = []
    for part in split(tokens):
        colon = next(i for i, t in enumerate(part) if t.value == ':')
        name = part[colon - 1].value
        kind = ''.join(t.value for t in part[colon + 1:])
        if kind == 'LanguageManager.Language' or live and name == 'c':
            continue
        if kind not in ('Int', 'String'):
            raise Unsupported(f'unsupported facade parameter {function.name}/{name}: {kind}')
        result.append((name, kind))
    return result


def render_facade(generator, source_functions):
    resources = generator.resources
    output = [HEADER]
    for item in generator.inventory:
        if not item['complete']:
            continue
        name = item['function']
        source, function = source_functions[name]
        params = parameters(function, name.startswith('live_'))
        replacements = {}
        for _, _, (_, named) in calls(function.body, 'replacingOccurrences'):
            token = literal(named['of'])[1:-1]
            text = ''.join(t.value for t in named['with'])
            if text.startswith('String('):
                text = text[7:-1]
            replacements[token] = text
        identities = [(kind, key) for kind, key in resources if key in item['resources']]
        plural = next((identity for identity in identities if identity[0] == 'plurals'), None)
        kind, key = plural or identities[0]
        resource = resources[kind, key]
        from generate import placeholder_schema
        schema = placeholder_schema(resource.values['en'].values(), resource.integer_tokens)
        missing = set(schema) - set(replacements)
        for token in sorted(missing):
            if token not in dict(params):
                params.append((token, 'String'))
            replacements[token] = token
        args = [replacements[token] for token in schema]
        if any(arg not in dict(params) for arg in args):
            raise Unsupported(f'unbound facade argument {name}: {args}')
        escaped = lambda n: '`' + n + '`' if n in ('when', 'in', 'is', 'object') else n
        signature = ', '.join(escaped(n) + ': ' + t for n, t in params)
        arguments = ', '.join(escaped(arg) for arg in args)
        rkey = key.replace('.', '_')
        if kind == 'plurals':
            count = next(n for n, t in params if t == 'Int')
            expression = f'plural(R.plurals.{rkey}, {escaped(count)}'
        else:
            expression = f'tr(R.string.{rkey}'
        if arguments:
            expression += ', ' + arguments
        expression += ')'
        output += [f'    // iOS: {source.rsplit("/", 1)[-1]}:{function.line}\n',
                   f'    fun {name}({signature}): String = {expression}\n']
    output.append('}\n')
    return ''.join(output)


def render_token_rules(generator):
    from generate import placeholder_schema
    rules = {}
    for item in generator.inventory:
        source, function = generator.source_functions[item['function']]
        order = []
        for _, _, (_, named) in calls(function.body, 'replacingOccurrences'):
            try:
                key = literal(named['of'])
            except Unsupported:
                continue
            if key.startswith('{') and key.endswith('}'):
                order.append(key[1:-1])
        for key in item['resources']:
            resource = generator.resources.get(('string', key), generator.resources.get(('plurals', key)))
            if resource is None:
                continue
            schema = placeholder_schema(resource.values['en'].values(), resource.integer_tokens)
            if schema and not resource.foundation_format:
                tokens = list(schema)
                filtered = list(dict.fromkeys(t for t in order if t in schema))
                if set(filtered) != set(tokens):
                    filtered = tokens
                rules[resource.kind, key] = (tokens, filtered)
    rules['string', 'logic_cosmeticRetainedChoice'] = (['kind', 'name'], ['kind', 'name'])
    output = ['// Generated by tools/strings/generate.py. iOS: AppStrings token replacements.\n',
              'package com.onezee.triptrack.designsystem.strings\n\n',
              'import com.onezee.triptrack.designsystem.R\n\n',
              '// iOS: AppStrings.swift, replacingOccurrences(of:with:).\n',
              'internal object ResourceTokenRules {\n']
    for index, field in enumerate(('tokens', 'order')):
        output.append(f'    fun {field}(id: Int): List<String>? = when (id) {{\n')
        for (kind, key), rule in sorted(rules.items()):
            values = ', '.join('"' + token + '"' for token in rule[index])
            output.append(f'        R.{kind}.{key.replace(".", "_")} -> listOf({values})\n')
        output.append('        else -> null\n    }\n')
    output.append('}\n')
    return ''.join(output)
