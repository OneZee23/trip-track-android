#!/usr/bin/env python3
"""Copy the iOS pixel artwork without tracing or resampling it."""
from pathlib import Path
import argparse
import shutil
import json
import re
import xml.etree.ElementTree as ET


def vector(source: Path, target: Path) -> None:
    root = ET.parse(source).getroot()
    _, _, width, height = root.attrib["viewBox"].split()
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        '<!-- iOS: ' + source.parent.parent.name + '/' + source.name + ' -->',
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        f'    android:width="{width}dp" android:height="{height}dp"',
        f'    android:viewportWidth="{width}" android:viewportHeight="{height}">',
    ]
    for node in root:
        kind = node.tag.rsplit("}", 1)[-1]
        attrs = node.attrib
        if kind == "path":
            path = attrs["d"]
        elif kind == "rect":
            x, y = attrs.get("x", "0"), attrs.get("y", "0")
            w, h = attrs["width"], attrs["height"]
            path = f"M{x},{y}h{w}v{h}h-{w}z"
        else:
            raise ValueError(f"Unsupported SVG element: {source}: {kind}")
        lines.append(f'    <path android:fillColor="{attrs["fill"]}" android:pathData="{path}" />')
    lines.append("</vector>")
    target.write_text("\n".join(lines) + "\n")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("ios", type=Path)
    args = parser.parse_args()
    catalogue = args.ios / "TripTrack/Resources/Assets.xcassets"
    res = Path(__file__).resolve().parents[1] / "app/src/main/res"
    drawables = res / "drawable"
    bitmaps = res / "drawable-nodpi"
    drawables.mkdir(parents=True, exist_ok=True)
    bitmaps.mkdir(parents=True, exist_ok=True)
    for group, prefix in [("Badges", "badge_"), ("RoadScene", "road_")]:
        for source in sorted((catalogue / group).rglob("*.svg")):
            vector(source, drawables / (prefix + source.stem + ".xml"))
    # The 1× art is the authored pixel grid. nodpi and FilterQuality.None keep it intact.
    for image_set in sorted(catalogue.glob("*.imageset")):
        if not image_set.stem.startswith(("pixel_", "platform_")):
            continue
        candidates = sorted(image_set.glob("*.png"))
        source = next((p for p in candidates if "@1x" in p.name), None)
        source = source or next((p for p in candidates if "@" not in p.name), None)
        if source is None:
            raise ValueError(f"No original sprite: {image_set}")
        shutil.copyfile(source, bitmaps / (image_set.stem + ".png"))
    resources = res.parent / "resources"
    resources.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(args.ios / "TripTrack/Resources/VehicleCatalog.json", resources / "VehicleCatalog.json")
    region_source = (args.ios / "TripTrack/Utils/RegionDisplay.swift").read_text()
    regions = []
    for english, aliases, russian, short in re.findall(r'^\s*\("([^"]+)", \[([^\]]*)\], "([^"]+)", "([^"]+)"\),', region_source, re.MULTILINE):
        regions.append(dict(en=english, ru=short, names=[english, russian, short] + re.findall(r'"([^"]+)"', aliases)))
    if not regions:
        raise ValueError("RegionDisplay subject table is empty")
    (resources / "ProfileRegions.json").write_text(json.dumps(regions, ensure_ascii=False, indent=2) + "\n")
    kotlin = res.parent / "kotlin/com/onezee/triptrack/feature/me/MeArtwork.kt"
    entries = sorted(p.stem for p in drawables.glob("*.xml") if p.stem.startswith(("badge_", "road_")))
    entries += sorted(p.stem for p in bitmaps.glob("*.png"))
    kotlin.write_text('// iOS: Assets.xcassets. Generated by tools/port_me_assets.py.\n'
                      'package com.onezee.triptrack.feature.me\n\nimport com.onezee.triptrack.R\n\n'
                      'internal object MeArtwork {\n    val drawables = mapOf(\n' +
                      ''.join(f'        "{name}" to R.drawable.{name},\n' for name in entries) +
                      '    )\n    val badgeTitles = mapOf(\n' +
                      ''.join(f'        "{source.stem}" to com.onezee.triptrack.designsystem.R.string.badge_{source.stem}_title,\n'
                              for source in sorted((catalogue / "Badges").rglob("*.svg"))) +
                      '    )\n    val badgeDescriptions = mapOf(\n' +
                      ''.join(f'        "{source.stem}" to com.onezee.triptrack.designsystem.R.string.badge_{source.stem}_description,\n'
                              for source in sorted((catalogue / "Badges").rglob("*.svg"))) +
                      '    )\n}\n')


if __name__ == "__main__":
    main()
